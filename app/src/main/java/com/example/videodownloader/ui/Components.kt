fun readClipboard(context: Context): String? {
    val cm = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
    val clip = cm.primaryClip ?: return null
    if (clip.itemCount == 0) return null
    return clip.getItemAt(0).coerceToText(context)?.toString()
}

fun openItem(context: Context, item: DownloadItem) {
    val uri = item.outputUri?.let { Uri.parse(it) } ?: return
    val intent = Intent(Intent.ACTION_VIEW).apply {
        setDataAndType(uri, item.mimeType ?: "*/*")
        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
    }
    try {
        context.startActivity(intent)
    } catch (e: Exception) {
        Toast.makeText(context, "Tidak ada aplikasi pemutar yang cocok.", Toast.LENGTH_SHORT).show()
    }
}

fun shareItem(context: Context, item: DownloadItem) {
    val uri = item.outputUri?.let { Uri.parse(it) } ?: return
    val send = Intent(Intent.ACTION_SEND).apply {
        type = item.mimeType ?: "*/*"
        putExtra(Intent.EXTRA_STREAM, uri)
        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
    }
    try {
        context.startActivity(Intent.createChooser(send, "Bagikan"))
    } catch (e: Exception) {
        Toast.makeText(context, "Tidak bisa membagikan berkas ini.", Toast.LENGTH_SHORT).show()
    }
}
